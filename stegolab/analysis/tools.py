def _environment(cwd: Path) -> dict[str, str]:
    """Do not copy API keys, tokens, proxy credentials or arbitrary server env."""
    env = {"PATH": os.environ.get("PATH", os.defpath), "LANG": "C.UTF-8", "LC_ALL": "C.UTF-8", "HOME": str(cwd), "TMPDIR": str(cwd), "TEMP": str(cwd), "TMP": str(cwd), "OMP_THREAD_LIMIT": "1", "OMP_NUM_THREADS": "1", "MAGICK_THREAD_LIMIT": "1", "MAGICK_MEMORY_LIMIT": "128MiB", "MAGICK_MAP_LIMIT": "128MiB", "MAGICK_DISK_LIMIT": "0", "MAGICK_TIME_LIMIT": "15", "MAGICK_WIDTH_LIMIT": "20000", "MAGICK_HEIGHT_LIMIT": "20000", "MAGICK_AREA_LIMIT": "32MP"}
    if os.name == "nt" and "SystemRoot" in os.environ:
        env["SystemRoot"] = os.environ["SystemRoot"]
    return env


def run_command(command: list[str], cwd: Path, timeout: float = TOOL_TIMEOUT,
                max_output: int = MAX_OUTPUT) -> dict:
    """Drain both pipes concurrently; stop on wall time or aggregate output cap."""
    started = time.monotonic()
    chunks: dict[str, list[bytes]] = {"stdout": [], "stderr": []}
    used = 0
    lock = threading.Lock()
    exceeded = threading.Event()
    def child_limits():
        import resource
        # CLI tools only emit bounded diagnostics or an audit file. Prevent a
        # decoder/audit writer from consuming the whole job's artifact quota.
        soft, hard = resource.getrlimit(resource.RLIMIT_FSIZE)
        new_limit = max_output if hard == resource.RLIM_INFINITY else min(hard, max_output)
        resource.setrlimit(resource.RLIMIT_FSIZE, (new_limit, new_limit))

    def kill_process_tree():
        # Keep tools in the worker process group so supervisor cancellation kills
        # everything. On Linux also stop known descendants at per-tool timeout.
        if os.name == "posix" and Path("/proc").is_dir():
            parents = {}
            for item in Path("/proc").iterdir():
                if item.name.isdigit():
                    try:
                        fields = (item / "stat").read_text().rsplit(")", 1)[1].split()
                        parents[int(item.name)] = int(fields[1])
                    except (OSError, ValueError, IndexError):
                        pass
            descendants = {proc.pid}
            for _ in range(32):
                expanded = descendants | {pid for pid, parent in parents.items() if parent in descendants}
                if expanded == descendants:
                    break
                descendants = expanded
            for pid in sorted(descendants - {proc.pid}, reverse=True):
                try:
                    os.kill(pid, signal.SIGKILL)
                except OSError:
                    pass
        try:
            proc.kill()
        except OSError:
            pass

    try:
        proc = subprocess.Popen(command, cwd=str(cwd), stdin=subprocess.DEVNULL,
                                stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                                shell=False, env=_environment(cwd),
                                preexec_fn=child_limits if os.name == "posix" else None)
    except (OSError, ValueError) as exc:
        return {"status": "failed", "stdout": "", "stderr": str(exc), "returncode": None, "duration_ms": round((time.monotonic() - started) * 1000)}

    def drain(stream, name):
        nonlocal used
        try:
            while True:
                piece = stream.read(8192)
                if not piece:
                    return
                with lock:
                    remaining = max_output - used
                    if remaining > 0:
                        chunks[name].append(piece[:remaining])
                        used += min(len(piece), remaining)
                    if len(piece) > remaining:
                        exceeded.set()
                        kill_process_tree()
        except (OSError, ValueError):
            return
        finally:
            stream.close()

    readers = [threading.Thread(target=drain, args=(proc.stdout, "stdout"), daemon=True), threading.Thread(target=drain, args=(proc.stderr, "stderr"), daemon=True)]
    for reader in readers:
        reader.start()
    timed_out = False
    try:
        proc.wait(timeout=timeout)
    except subprocess.TimeoutExpired:
        timed_out = True
        kill_process_tree()
        proc.wait(timeout=3)
    for reader in readers:
        reader.join(timeout=2)
    status = "timeout" if timed_out else "partial" if exceeded.is_set() else "completed" if proc.returncode == 0 else "failed"
    return {"status": status, "stdout": b"".join(chunks["stdout"]).decode("utf-8", "replace"), "stderr": b"".join(chunks["stderr"]).decode("utf-8", "replace"), "returncode": proc.returncode, "output_truncated": exceeded.is_set(), "duration_ms": round((time.monotonic() - started) * 1000)}


def registry_snapshot() -> list[dict]:
    records = []
    for name, spec in SPECS.items():
        executable = next((shutil.which(candidate) for candidate in spec["executables"] if shutil.which(candidate)), None)
        if spec.get('blocked'):
            executable = None
        version = None
        if executable:
            try:
                # Some CLIs initialize ~/.config even for --help. /app is read
                # only in production, so every probe gets a temporary HOME/cwd.
                with tempfile.TemporaryDirectory(prefix="stegolab-probe-") as directory:
                    cwd = Path(directory)
                    result = run_command([executable, *spec["version_args"]], cwd, timeout=3, max_output=8192)
                    lines = (result["stdout"] + "\n" + result["stderr"]).strip().splitlines()
                    version = next((line.strip() for line in lines if line.strip()), "version not reported")[:240]
                    if name=='stegoveritas':
                        interpreter=Path(executable).resolve().with_name('python')
                        if interpreter.exists():
                            metadata=run_command([str(interpreter),'-c',"from importlib.metadata import version;print(version('stegoveritas'))"],cwd,timeout=3,max_output=8192)
                            if metadata['status']=='completed':version=metadata['stdout'].strip()[:240]
                    if any(term in result['stdout']+result['stderr'] for term in ('Traceback (most recent call last)','OpenStegoException','Could not create the Java Virtual Machine')):
                        executable=None
                        version='Executable failed its compatibility probe'
                    if name == "zsteg" and ("unknown" in version.lower() or version == "version not reported"):
                        ruby = shutil.which("ruby")
                        if ruby:
                            gem = run_command([ruby, "-e", "puts Gem::Specification.find_by_name('zsteg').version"], cwd, timeout=3, max_output=8192)
                            if gem["status"] == "completed" and gem["stdout"].strip():
                                version = gem["stdout"].strip()[:240]
            except OSError as exc:
                version = f"Version probe unavailable: {type(exc).__name__}"
        records.append({"name": name, "version": version, "formats": spec["formats"], "available": bool(executable), "executable": executable, "parameters": spec["parameters"], "limits": {"timeout_seconds": TOOL_TIMEOUT, "output_bytes": MAX_OUTPUT, "max_child_file_bytes": MAX_OUTPUT, "shell": False, "environment": "allowlist; no inherited application secrets", "cpu_memory": "Inherited worker CPU/address-space and Docker limits (default 768 MiB per job)"}, "parser": spec["parser"], "error_handling": "Return unavailable, timeout, failed or partial with bounded diagnostics; continue remaining analyzers."})
        records[-1].update({key:spec[key] for key in ('license','source','installation','blocked','manual') if key in spec})
    return records


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--registry", type=Path, required=True)
    args = parser.parse_args()
    args.registry.parent.mkdir(parents=True, exist_ok=True)
    temporary = args.registry.with_suffix(".tmp")
    temporary.write_text(json.dumps(registry_snapshot(), indent=2), encoding="utf-8")
    temporary.replace(args.registry)


if __name__ == "__main__":
    main()
